"""OpenBao initialization capability.

Initialize a fresh Shamir-sealed OpenBao instance through its HTTPS API.

Initialization generates sensitive unseal keys and an initial root token.
These are returned to the caller without logging or persistence.

Initialization is non-idempotent. Once the request has been attempted,
transport failures or invalid responses have an uncertain outcome and
must never trigger an automatic retry.
"""

from __future__ import annotations

import base64
import binascii
import http.client
import json
import ssl
from dataclasses import dataclass, field
from typing import cast
from urllib.parse import urlsplit

from mxm.control.openbao.api import OpenBaoError, validated_address
from mxm.control.openbao.status import status_openbao

_MAX_RESPONSE_BYTES = 64 * 1024


class OpenBaoInitializationUncertainError(OpenBaoError):
    """Initialization may have succeeded, but authority was not recovered."""


@dataclass(frozen=True, repr=False)
class OpenBaoInitialization:
    """Sensitive authority generated by OpenBao initialization.

    Attributes:
        unseal_keys: Base64-encoded Shamir unseal-key shares.
        root_token: Initial OpenBao root token.

    This object must not be logged, serialized, or persisted implicitly.
    Its caller is responsible for secure handling and delivery.
    """

    unseal_keys: tuple[str, ...] = field(repr=False)
    root_token: str = field(repr=False)


def _validate_configuration(shares: int, threshold: int) -> None:
    """Validate a Shamir initialization configuration."""
    if type(shares) is not int or type(threshold) is not int:
        raise OpenBaoError("shares and threshold must be integers")

    if not 1 <= threshold <= shares <= 255:
        raise OpenBaoError("initialization requires 1 <= threshold <= shares <= 255")


def _parse_initialization(
    payload: bytes,
    *,
    shares: int,
) -> OpenBaoInitialization:
    """Validate the sensitive initialization response without exposing it."""
    try:
        document: object = json.loads(payload)
    except (ValueError, UnicodeDecodeError) as exc:
        raise OpenBaoInitializationUncertainError(
            "OpenBao initialization returned invalid JSON; do not retry automatically"
        ) from exc

    if not isinstance(document, dict):
        raise OpenBaoInitializationUncertainError(
            "OpenBao initialization returned an invalid response"
        )

    data = cast("dict[str, object]", document)
    keys = data.get("keys_base64")
    token = data.get("root_token")

    if not isinstance(keys, list):
        raise OpenBaoInitializationUncertainError(
            "OpenBao initialization response lacks expected unseal keys; "
            "do not retry automatically"
        )

    unseal_keys = cast("list[object]", keys)

    if (
        len(unseal_keys) != shares
        or any(type(key) is not str or not key for key in unseal_keys)
        or type(token) is not str
        or not token
    ):
        raise OpenBaoInitializationUncertainError(
            "OpenBao initialization response lacks expected authority; "
            "do not retry automatically"
        )
    validated_keys = cast("list[str]", unseal_keys)

    try:
        for key in validated_keys:
            if not base64.b64decode(key, validate=True):
                raise ValueError("empty unseal key")
    except (ValueError, binascii.Error) as exc:
        raise OpenBaoInitializationUncertainError(
            "OpenBao initialization returned invalid unseal-key encoding; "
            "do not retry automatically"
        ) from exc
    return OpenBaoInitialization(
        unseal_keys=tuple(validated_keys),
        root_token=token,
    )


def _post_initialization(
    address: str,
    *,
    shares: int,
    threshold: int,
    timeout: float,
) -> bytes:
    """Submit initialization exactly once through verified HTTPS.

    The standard-library HTTPS client does not automatically follow
    redirects. The response size is bounded, including on error paths.

    After the request is attempted, failures are treated as uncertain
    because the server may have completed initialization.
    """
    origin = urlsplit(address)
    hostname = origin.hostname

    if hostname is None:
        raise OpenBaoError("OpenBao service address has no hostname")

    body = json.dumps(
        {
            "secret_shares": shares,
            "secret_threshold": threshold,
        }
    ).encode("utf-8")

    connection = http.client.HTTPSConnection(
        host=hostname,
        port=origin.port or 443,
        timeout=timeout,
        context=ssl.create_default_context(),
    )

    try:
        connection.request(
            "POST",
            "/v1/sys/init",
            body=body,
            headers={
                "Content-Type": "application/json",
                "Accept": "application/json",
            },
        )

        response = connection.getresponse()
        payload = response.read(_MAX_RESPONSE_BYTES + 1)

        if response.status != 200 or len(payload) > _MAX_RESPONSE_BYTES:
            raise OpenBaoInitializationUncertainError(
                "OpenBao initialization did not return a valid success "
                "response; inspect instance state before recovery"
            )

        return payload

    except (OSError, http.client.HTTPException) as exc:
        raise OpenBaoInitializationUncertainError(
            "OpenBao initialization outcome is uncertain; do not retry automatically"
        ) from exc

    finally:
        connection.close()


def initialise_openbao(
    address: str,
    *,
    shares: int,
    threshold: int,
    timeout: float = 10.0,
) -> OpenBaoInitialization:
    """Initialize a previously uninitialized Shamir-sealed OpenBao instance.

    Args:
        address: HTTPS origin of the target OpenBao service.
        shares: Number of Shamir unseal-key shares to generate.
        threshold: Shares required to unseal the instance.
        timeout: Network timeout in seconds.

    Returns:
        Sensitive initial root authority and unseal-key shares.

    Raises:
        OpenBaoError: If validation or preflight fails.
        OpenBaoInitializationUncertainError: If initialization may have
            succeeded but its authority could not be recovered.

    The caller must securely handle the returned authority. This
    function does not unseal the instance or establish an operator session.
    """
    origin = validated_address(address)
    _validate_configuration(shares, threshold)

    if timeout <= 0:
        raise OpenBaoError("OpenBao timeout must be positive")

    status = status_openbao(origin, timeout=timeout)

    if status.initialized:
        raise OpenBaoError("OpenBao instance is already initialized")

    payload = _post_initialization(
        origin,
        shares=shares,
        threshold=threshold,
        timeout=timeout,
    )

    # Do not perform another network request before returning the
    # generated secrets. A failed postcondition check must not cause
    # successfully received authority to be lost.
    return _parse_initialization(payload, shares=shares)


__all__ = [
    "OpenBaoInitialization",
    "OpenBaoInitializationUncertainError",
    "initialise_openbao",
]
